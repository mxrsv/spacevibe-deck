import { shellQuote } from "../agent-hooks/claude-hooks-file";

/** Verified against V1 1.18.29/1.19.3 and V2 2.0.32. Unknown forms stay inferred. */
export function opencodeWrapperBranch(markerPath: string, configDir: string): string[] {
  return [
    "oc_local=1",
    "oc_mode=",
    "oc_take=",
    "oc_standalone=",
    "oc_v1_only=",
    "oc_v2_only=",
    'for arg in "$@"; do',
    '  if [ -n "$oc_take" ]; then oc_take=; continue; fi',
    '  [ "$arg" = -- ] && break',
    '  case "$arg" in',
    "    --server|--attach) oc_local=; oc_take=1 ;;",
    "    --server=*|--attach=*|--help|-h|--version|-v|--pure) oc_local= ;;",
    "    --standalone) oc_standalone=1; oc_v2_only=1 ;;",
    "    --session|-s|--model|-m|--agent|--prompt|--format|--title|--file|-f|--log-level|--replay-limit) oc_take=1 ;;",
    "    --session=*|--model=*|--agent=*|--prompt=*|--format=*|--title=*|--file=*|--log-level=*|--replay-limit=*) ;;",
    "    --dir|--variant|--command) oc_v1_only=1; oc_take=1 ;;",
    "    --dir=*|--variant=*|--command=*|--mini|--interactive|-i) oc_v1_only=1 ;;",
    "    --continue|-c|--fork|--auto|--thinking|--print-logs|--no-replay) ;;",
    "    --replay) oc_v2_only=1 ;;",
    "    -*) oc_local= ;;",
    '    *) if [ -z "$oc_mode" ]; then',
    '         case "$arg" in',
    '           run|mini) oc_mode=$arg; [ "${1-}" = "$arg" ] || oc_local= ;;',
    '           *) oc_mode=root; [ -d "$arg" ] || oc_local= ;;',
    "         esac",
    '       elif [ "$oc_mode" != run ]; then oc_local=; fi ;;',
    "  esac",
    "done",
    '[ -z "$oc_take" ] || oc_local=',
    "oc_supported=",
    `if [ -n "$oc_local" ] && [ -z "\${DECK_AGENT_NESTED-}" ] && [ -e ${shellQuote(markerPath)} ]; then`,
    // Each probe has its own environment and watchdog; no global cache survives PATH changes.
    // The watchdog allows 5 s: macOS checks a new binary on its first exec, which took 2.1-2.2 s
    // for opencode 2.0.32 (2026-10-24), and a probe killed then drops Signals for that launch.
    "  deck_oc_probe() (",
    "    unset DECK_PANE_ID DECK_HOOK_TOKEN DECK_HOOK_PORT DECK_AGENT_ID DECK_AGENT_PID DECK_AGENT_NESTED OPENCODE_CONFIG_DIR",
    '    "$real" "$@" </dev/null &',
    "    oc_probe=$!",
    "    (",
    "      command -p sleep 5 &",
    "      oc_sleep=$!",
    "      trap 'kill \"$oc_sleep\" 2>/dev/null; exit' TERM",
    '      wait "$oc_sleep"',
    '      kill -KILL "$oc_probe" 2>/dev/null',
    "    ) >/dev/null 2>&1 &",
    "    oc_timer=$!",
    '    wait "$oc_probe"',
    "    oc_result=$?",
    '    kill "$oc_timer" 2>/dev/null',
    '    wait "$oc_timer" 2>/dev/null',
    '    exit "$oc_result"',
    "  )",
    "  oc_version=$(deck_oc_probe --version 2>/dev/null) || oc_version=",
    "  oc_version=${oc_version#opencode v}",
    '  if printf "%s\\n" "$oc_version" | command -p grep -Eq "^[12]\\.(0|[1-9][0-9]{0,5})\\.(0|[1-9][0-9]{0,5})$"; then',
    "    oc_major=${oc_version%%.*}; oc_tail=${oc_version#*.}",
    "    oc_minor=${oc_tail%%.*}; oc_patch=${oc_tail#*.}",
    '    if [ "$oc_major" = 1 ] && [ -z "$oc_v2_only" ] && [ "$oc_mode" != mini ]; then',
    '      if [ "$oc_minor" -gt 18 ] || { [ "$oc_minor" -eq 18 ] && [ "$oc_patch" -ge 29 ]; }; then oc_supported=1; fi',
    '    elif [ "$oc_major" = 2 ] && [ -z "$oc_v1_only" ]; then',
    '      case "$oc_mode" in',
    '        run|mini) oc_help=$(deck_oc_probe "$oc_mode" --help 2>/dev/null) || oc_help= ;;',
    "        *) oc_help=$(deck_oc_probe --help 2>/dev/null) || oc_help= ;;",
    "      esac",
    '      case "$oc_help" in *--standalone*) oc_supported=1 ;; esac',
    '      if [ -n "$oc_supported" ] && [ -z "$oc_standalone" ]; then',
    // V2 rejects a parent flag before a subcommand; never append after a prompt's `--`.
    '        case "$oc_mode" in',
    '          run|mini) shift; set -- "$oc_mode" --standalone "$@" ;;',
    '          *) set -- --standalone "$@" ;;',
    "        esac",
    "      fi",
    "    fi",
    "  fi",
    "fi",
    'if [ -n "$oc_supported" ]; then',
    `  OPENCODE_CONFIG_DIR=${shellQuote(configDir)}`,
    "  export OPENCODE_CONFIG_DIR",
    "else",
    // A default V2 launch can start a long-lived shared service even with Signals off.
    "  unset DECK_PANE_ID DECK_HOOK_TOKEN DECK_HOOK_PORT",
    `  if [ -z "\${DECK_AGENT_NESTED-}" ] && [ "\${OPENCODE_CONFIG_DIR-}" = ${shellQuote(configDir)} ]; then unset OPENCODE_CONFIG_DIR; fi`,
    "fi",
  ];
}
