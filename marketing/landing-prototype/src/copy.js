export function resolveLocale(search, navigatorLanguage) {
  const override = new URLSearchParams(search).get("lang");

  if (override === "en" || override === "vi") {
    return override;
  }

  return navigatorLanguage.toLowerCase().startsWith("vi") ? "vi" : "en";
}
