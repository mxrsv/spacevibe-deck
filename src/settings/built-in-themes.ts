/*
 * The eight themes Deck ships. Every value is explicit (spec THM-1): nothing
 * here is computed at runtime, so a theme looks the same in the app, the
 * editor, the gallery and a theme card. The washes and seams on top of these
 * surfaces are formulas (`deriveChromeColors`), not theme values.
 *
 * Contrast is a test, not a repair: `built-in-themes.test.ts` holds every theme
 * to DL-3.5's text floors and the ANSI floors, and keeps the dark themes
 * visibly apart from each other.
 */

